#!/usr/bin/env python3
"""Generate an RVF2 Ode to Joy melody clip and a matching WAV preview.

The short melody is synthesized here; no third-party recording is included.
Python standard library only. Uses the existing 48 kHz mono mu-law format.
"""
import argparse
import array
import hashlib
import json
import math
from pathlib import Path
import sys
import wave

from convert_video import WIDTH, HEIGHT, header, audio_layout, pcm16_to_ulaw


NOTES = [
    (64, 1), (64, 1), (65, 1), (67, 1), (67, 1), (65, 1), (64, 1), (62, 1),
    (60, 1), (60, 1), (62, 1), (64, 1), (64, 1.5), (62, .5), (62, 2),
    (64, 1), (64, 1), (65, 1), (67, 1), (67, 1), (65, 1), (64, 1), (62, 1),
    (60, 1), (60, 1), (62, 1), (64, 1), (62, 1.5), (60, .5), (60, 2),
]
RATE, FPS, BEAT = 48000, 3, .5


def synthesize():
    pcm = array.array('h')
    timeline = []
    for midi, beats in NOTES:
        start = len(pcm)
        count = round(beats * BEAT * RATE)
        timeline.append((start / RATE, (start + count) / RATE, midi))
        frequency = 440 * 2 ** ((midi - 69) / 12)
        for i in range(count):
            t = i / RATE
            # Smooth attacks/releases avoid clicks. Harmonics make each note
            # easier to recognize than a single-frequency beeper test.
            envelope = min(1, t / .012, (count - 1 - i) / (RATE * .045))
            envelope *= .72 + .28 * math.exp(-4 * t)
            angle = 2 * math.pi * frequency * t
            tone = math.sin(angle) + .22 * math.sin(2 * angle) + .08 * math.sin(3 * angle)
            pcm.append(round(10500 * envelope * tone))
    if sys.byteorder != 'little':
        pcm.byteswap()
    return pcm.tobytes(), timeline


def picture(frame, timeline):
    t = frame / FPS
    midi = next(note for start, end, note in timeline if start <= t < end)
    pixels = bytearray(bytes([0x02]) * WIDTH * HEIGHT)

    def rect(x, y, width, height, color):
        row = bytes([color]) * width
        for line in range(y, min(HEIGHT, y + height)):
            pixels[line * WIDTH + x:line * WIDTH + x + width] = row

    # All useful content is above the firmware's bottom menu overlay.
    for k, note in enumerate([60, 62, 64, 65, 67, 69, 71, 72]):
        rect(24 + k * 74, 180, 66, 180, 0x1c if note == midi else 0xff)
        rect(24 + k * 74, 345, 66, 15, 0x14 if note == midi else 0xb6)
    # A bouncing marker and progress bar distinguish this from the old bars.
    rect(24 + round(frame / 47 * 570), 60 + (frame % 3) * 20, 22, 22, 0xfc)
    rect(24, 120, 592, 12, 0x49)
    rect(24, 120, max(1, round(592 * (frame + 1) / 48)), 12, 0x1f)
    return pixels


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path, help='new or empty output directory')
    args = parser.parse_args()
    args.directory.mkdir(parents=True, exist_ok=True)
    paths = [args.directory / name for name in ('VIDEO.RV', 'ODE_TO_JOY.wav', 'music.json')]
    if any(p.exists() for p in paths):
        parser.error('output already exists; choose a new directory to preserve existing files')
    pcm, timeline = synthesize()
    samples, audio_bytes = audio_layout(FPS)
    assert len(pcm) == 16 * RATE * 2
    with paths[0].open('wb') as out:
        out.write(header(48, FPS, True))
        for frame in range(48):
            out.write(picture(frame, timeline))
            block = pcm[frame * samples * 2:(frame + 1) * samples * 2]
            out.write(pcm16_to_ulaw(block).ljust(audio_bytes, b'\xff'))
    with wave.open(str(paths[1]), 'wb') as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(RATE)
        out.writeframes(pcm)
    manifest = {
        'title': 'Ode to Joy — synthesized melody with animated piano keys',
        'composition': 'Ludwig van Beethoven, Ode to Joy (1824)',
        'recording': 'Generated by tools/make_music_demo.py; no downloaded recording',
        'reference': 'https://commons.wikimedia.org/wiki/File:Ode_to_Joy.ogg',
        'duration_seconds': 16, 'fps': FPS, 'frames': 48,
        'video_format': 'RVF2, 640x480 RGB332', 'audio_format': '48 kHz mono mu-law',
        'requires': 'TF_MEDIA_SWITCH_FIX.bit or another RVF2-capable combined player; TF_VIDEO.bit is incompatible',
        'files': {p.name: {'bytes': p.stat().st_size,
                          'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
                  for p in paths[:2]},
    }
    paths[2].write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')
    print(json.dumps(manifest, indent=2, ensure_ascii=False))


if __name__ == '__main__':
    main()
